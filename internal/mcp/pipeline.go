package mcp

import (
	"context"
	"fmt"

	"connectrpc.com/connect"
	opendesignerv1 "github.com/bernardoforcillo/opendesigner/gen/opendesigner/v1"
	"github.com/bernardoforcillo/opendesigner/internal/codegen"
	"github.com/bernardoforcillo/opendesigner/internal/pipeline"
	"github.com/modelcontextprotocol/go-sdk/mcp"
)

// run_pipeline: prototype -> codegen -> Playwright in one call, with a result
// per flow (internal/pipeline; the same chain as `opendesigner pipeline`).

type RunPipelineInput struct {
	OutDir      string `json:"outDir,omitempty" jsonschema:"where to write the react project (default: a new temporary directory); must be empty unless force"`
	FlowId      string `json:"flowId,omitempty" jsonschema:"run a single flow (see list_flows); empty = all"`
	Force       bool   `json:"force,omitempty" jsonschema:"allow a non-empty outDir"`
	SkipInstall bool   `json:"skipInstall,omitempty" jsonschema:"node_modules and the Playwright browser are already installed in outDir"`
	NoTests     bool   `json:"noTests,omitempty" jsonschema:"stop after generating the project"`
}

// pipelineRunner runs npm/npx for run_pipeline; tests replace it.
var pipelineRunner pipeline.Runner = pipeline.ExecRunner{}

// RunPipeline analyses the flows, exports the react project (generated by the
// server, which owns the assets), installs it and runs the Playwright tests
// generated from the flows. Failures of a stage or of a test are part of the
// report (ok=false), not a tool error.
func (s *Session) RunPipeline(ctx context.Context, in RunPipelineInput) (*pipeline.Report, error) {
	resp, err := s.client.ExportCode(ctx, connect.NewRequest(&opendesignerv1.ExportCodeRequest{DocId: s.docID, Target: string(codegen.TargetReact), FlowId: in.FlowId}))
	if err != nil {
		return nil, fmt.Errorf("run_pipeline: %w", err)
	}
	proj := &codegen.Output{Warnings: resp.Msg.GetWarnings()}
	for _, f := range resp.Msg.GetFiles() {
		proj.Files = append(proj.Files, codegen.File{Path: f.GetPath(), Content: f.GetContent()})
	}
	s.mu.Lock()
	doc := s.doc
	s.mu.Unlock()
	rep, err := pipeline.Run(ctx, doc, nil, pipeline.Options{
		FlowID: in.FlowId, OutDir: in.OutDir, Force: in.Force, SkipInstall: in.SkipInstall, SkipTests: in.NoTests,
		Project: proj, Runner: pipelineRunner,
	})
	if err != nil {
		return nil, fmt.Errorf("run_pipeline: %w", err)
	}
	return rep, nil
}

func registerPipelineTool(srv *mcp.Server, s *Session) {
	addTool(srv, "run_pipeline", "Run the whole chain prototype -> codegen -> Playwright in one call and get a result per flow: analyses the flows, exports the react project (as export_code), runs npm install and the Playwright browser install, then the Playwright tests generated from the flows. Returns the stages (prototype, codegen, install, playwright), per flow the passed / failed / skipped tests (skipped = test.fixme: set code.route and test.id / test.text with set_node_meta to make them run) with the failure messages, and ok. Needs node/npm and, the first time, network access; it can take minutes. Use skipInstall once outDir is installed, noTests to only generate.", s.RunPipeline)
}
